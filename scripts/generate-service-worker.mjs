import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export function precachePaths(files) {
  return files.map((file) => file.split(sep).join("/")).filter((file) =>
    file !== "sw.js" && file !== "_headers" && file !== "_redirects" && !file.endsWith(".map") && !file.endsWith(".php") &&
    !file.startsWith("api/") && !file.startsWith("404/") && file !== "404.html" &&
    !file.startsWith("_not-found/") && file !== "robots.txt" && file !== "sitemap.xml"
  ).map((file) => file === "index.html" ? "/" : `/${file.split("/").map(encodeURIComponent).join("/")}`).sort();
}

export function serviceWorkerSource(version, entries) {
  return `// Generated by scripts/generate-service-worker.mjs.
const VERSION = ${JSON.stringify(version)};
const PREFIX = "cadverix-offline-";
const CACHE = PREFIX + VERSION;
const READY = "/__cadverix_offline_ready__";
const ENTRIES = ${JSON.stringify(entries)};
const PATHS = new Set(ENTRIES.map(entry => entry.url));
let repair = null;

async function notify(message) {
  const clients = await self.clients.matchAll({ type: "window", includeUncontrolled: true });
  for (const client of clients) client.postMessage({ type: "CADVERIX_OFFLINE", version: VERSION, ...message });
}

async function status() {
  const cache = await caches.open(CACHE);
  const keys = new Set((await cache.keys()).map(request => new URL(request.url).pathname));
  return { type: "CADVERIX_OFFLINE", version: VERSION, ready: keys.has(READY) && ENTRIES.every(entry => keys.has(entry.url)), progress: ENTRIES.filter(entry => keys.has(entry.url)).length, total: ENTRIES.length, bytes: ENTRIES.reduce((sum, entry) => sum + entry.bytes, 0) };
}

async function cacheApplication(repairing = false) {
  const cache = await caches.open(CACHE);
  await cache.delete(READY);
  let next = 0, done = 0;
  const bytes = ENTRIES.reduce((sum, entry) => sum + entry.bytes, 0);
  await notify({ ready: false, progress: 0, total: ENTRIES.length, bytes });
  // Bound parallel downloads so a phone is not asked to fetch hundreds of
  // resources simultaneously. Include all WASM assets, including lazy workers.
  const results = await Promise.allSettled(Array.from({ length: 4 }, async () => {
    while (next < ENTRIES.length) {
      const entry = ENTRIES[next++];
      if (!repairing || !(await cache.match(entry.url))) {
        const response = await fetch(new Request(entry.url, { cache: "no-store", integrity: entry.integrity }));
        if (!response.ok) throw new Error("Offline asset unavailable: " + entry.url);
        await cache.put(entry.url, response);
      }
      done++;
      if (done % 10 === 0) await notify({ ready: false, progress: done, total: ENTRIES.length, bytes });
    }
  }));
  const failed = results.find(result => result.status === "rejected");
  if (failed) {
    if (!repairing) await caches.delete(CACHE);
    await notify({ ready: false, error: "Offline setup could not finish. Check your connection and available browser storage, then retry." });
    throw failed.reason;
  }
  await cache.put(READY, new Response(VERSION));
  await notify(await status());
}

self.addEventListener("install", event => {
  event.waitUntil(cacheApplication());
  // Deliberately no skipWaiting: an update must not replace the runtime of
  // an open editor or force a reload while a design is being changed.
});

self.addEventListener("activate", event => {
  event.waitUntil((async () => {
    const names = (await caches.keys()).filter(name => name.startsWith(PREFIX));
    const complete = [];
    for (const name of names) if (await (await caches.open(name)).match(READY)) complete.push(name);
    const keep = new Set([CACHE, ...complete.filter(name => name !== CACHE).slice(-1)]);
    await Promise.all(names.filter(name => !keep.has(name)).map(name => caches.delete(name)));
    await self.clients.claim();
    await notify(await status());
  })());
});

self.addEventListener("message", event => {
  if (event.data?.type === "CADVERIX_OFFLINE_STATUS") {
    event.waitUntil(status().then(value => event.ports[0]?.postMessage(value)));
  } else if (event.data?.type === "CADVERIX_OFFLINE_REPAIR") {
    repair ??= cacheApplication(true).finally(() => { repair = null; });
    event.waitUntil(repair.catch(() => {}));
  }
});

self.addEventListener("fetch", event => {
  const request = event.request;
  const url = new URL(request.url);
  if (request.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/") || url.pathname.endsWith(".php") || url.pathname === "/sw.js") return;
  const navigation = request.mode === "navigate" && (url.pathname === "/" || url.pathname === "/index.html");
  const path = navigation ? "/" : url.pathname;
  if (!navigation && !PATHS.has(path)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const response = await cache.match(path);
    if (response) return response;
    // A missing/evicted resource must not leave a false offline-ready marker.
    await cache.delete(READY);
    await notify({ ready: false, error: "Some offline files are missing. Reconnect and retry offline setup." });
    return fetch(request);
  })());
});
`;
}

async function listFiles(root) {
  const entries = await readdir(root, { withFileTypes: true });
  return (await Promise.all(entries.map((entry) => entry.isDirectory() ? listFiles(join(root, entry.name)) : [join(root, entry.name)]))).flat();
}

export async function generateServiceWorker(exportRoot) {
  const paths = precachePaths((await listFiles(exportRoot)).map((file) => relative(exportRoot, file)));
  if (!paths.includes("/") || !paths.includes("/manifest.webmanifest") || !paths.includes("/occt/occt-wasm.wasm")) throw new Error("Static export is missing required offline app assets");
  const entries = await Promise.all(paths.map(async (url) => {
    const bytes = await readFile(join(exportRoot, url === "/" ? "index.html" : decodeURIComponent(url.slice(1))));
    return { url, integrity: `sha256-${createHash("sha256").update(bytes).digest("base64")}`, bytes: bytes.length };
  }));
  const version = createHash("sha256").update(serviceWorkerSource("BUILD", entries)).digest("hex").slice(0, 20);
  await writeFile(join(exportRoot, "sw.js"), serviceWorkerSource(version, entries));
  console.log(`Offline app: ${entries.length} assets, ${(entries.reduce((sum, entry) => sum + entry.bytes, 0) / 1024 / 1024).toFixed(1)} MiB, version ${version}`);
  return { version, entries };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await generateServiceWorker(join(dirname(dirname(fileURLToPath(import.meta.url))), "apps/web/.next-export"));
}
